/**
 * 每个页面的内容与操作指南（V15）。
 *
 * ## 为什么做成注册表而不是每页写一个组件
 *
 * 改造前只有 5 个页面挂了 `HelpTriggerButton`，其余 20 多个页面没有——
 * 因为每挂一个都要在那个页面里写一段 JSX，而**「顺手写一段」是不会发生的**。
 *
 * 做成注册表之后：指南是数据，触发按钮放在全局顶栏（`AppLayout`），
 * 每个页面自动就有。新页面漏写指南由 `page-guides.test.ts` 拦下。
 *
 * ## 一份数据，两处消费
 *
 * 1. **每页右上角的浮层**——「这一页是干什么的、怎么用」
 * 2. **系统设置 → 关于系统里的完整手册**——把全部页面的指南连起来读
 *
 * 分两份写迟早不一致，而不一致的手册比没有手册更误导。
 *
 * ## 写指南的三条要求
 *
 * - `purpose` 说**这一页回答什么问题**，不是罗列有哪些按钮
 * - `steps` 是**按顺序做的事**，不是功能清单
 * - `caution` 只写**做错了会怎样**，不写「请谨慎操作」这种没有信息量的话
 */

export interface PageGuide {
  /** 路由。与 `nav-filter.ts` 的 key、后端菜单的 route 是同一套。 */
  route: string;
  title: string;
  /** 谁会用这一页。写角色，不写「所有人」。 */
  audience: string;
  /** 这一页回答什么问题。 */
  purpose: string;
  /** 按顺序做的事。 */
  steps: readonly string[];
  /** 做错了会怎样。没有就留空数组，不要凑。 */
  caution?: readonly string[];
  /** 上下游：这一页的数据从哪来、做完去哪。 */
  flow?: string;
}

